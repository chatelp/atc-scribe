#!/usr/bin/env node
// Checks the design tokens (docs-fr/design/jetons.json) and writes them out.
//
//   node tools/design/tokens.mjs
//
// - writes docs-fr/design/maquettes/tokens.css (CSS custom properties, the
//   mock-ups' only source of values);
// - writes docs-fr/design/03-systeme-verif.md: every text token on every
//   surface it may sit on (WCAG 2.1), the non-text contrasts (control outlines,
//   focus ring, status lights, map icons), and how far apart the meaningful
//   palettes stay under normal sight and the three dichromacies;
// - exits with 1 when a required check fails, so a token cannot drift below
//   what 02-principes.md promises.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { contrast, deltaE, simulate, CVD, lab, parseColor } from './color.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const src = path.join(root, 'docs-fr/design/jetons.json');
const cssOut = path.join(root, 'docs-fr/design/maquettes/tokens.css');
const mdOut = path.join(root, 'docs-fr/design/03-systeme-verif.md');
const tokens = JSON.parse(fs.readFileSync(src, 'utf8'));

// ---------------------------------------------------------------- flatten

const flat = new Map(); // 'color.text.primary' -> value
(function walk(node, trail) {
    for (const [k, v] of Object.entries(node)) {
        if (k.startsWith('$')) continue;
        if (v && typeof v === 'object' && '$value' in v) flat.set([...trail, k].join('.'), v.$value);
        else if (v && typeof v === 'object') walk(v, [...trail, k]);
    }
})(tokens, []);
const get = (k) => { if (!flat.has(k)) throw new Error(`no token ${k}`); return flat.get(k); };
const hex = (k) => parseColor(get(k)).split('@')[0];

// ---------------------------------------------------------------- CSS

const cssName = (k) => '--' + k.replace(/\./g, '-');
const cssValue = (k, v) => {
    if (Array.isArray(v)) return `cubic-bezier(${v.join(', ')})`;
    return String(v);
};
const css = [
    '/* Generated by tools/design/tokens.mjs from docs-fr/design/jetons.json. Do not edit. */',
    ':root {',
    ...[...flat.entries()].map(([k, v]) => `    ${cssName(k)}: ${cssValue(k, v)};`),
    '}',
    '',
];
fs.mkdirSync(path.dirname(cssOut), { recursive: true });
fs.writeFileSync(cssOut, css.join('\n'));

// ---------------------------------------------------------------- checks

const out = [];
const p = (s = '') => out.push(s);
let failures = 0;
const mark = (ok) => { if (!ok) failures++; return ok ? '' : ' ✗'; };
const r1 = (x) => x.toFixed(1);

p('# Vérification des jetons — générée par tools/design/tokens.mjs');
p();
p('Ne pas modifier à la main : régénérer après tout changement de `jetons.json`. ✗ = exigence non tenue (le script sort alors en erreur).');
p();

// Text on surfaces
const surfaces = ['page', 'panel', 'raised', 'hover', 'selected', 'urgent', 'warn'].map((s) => `color.surface.${s}`);
const textTokens = [
    ['color.text.primary', surfaces],
    ['color.text.secondary', surfaces],
    ['color.text.tertiary', surfaces],
    ['color.accent.default', ['page', 'panel', 'raised', 'hover', 'selected'].map((s) => `color.surface.${s}`)],
    ['color.accent.strong', ['page', 'panel', 'raised', 'hover', 'selected'].map((s) => `color.surface.${s}`)],
    ['color.status.urgent', ['page', 'panel', 'raised', 'hover', 'urgent'].map((s) => `color.surface.${s}`)],
    ['color.status.warn', ['page', 'panel', 'raised', 'hover', 'warn'].map((s) => `color.surface.${s}`)],
    ['color.status.info', ['page', 'panel', 'raised', 'hover'].map((s) => `color.surface.${s}`)],
    ...['ground', 'departure', 'cruise', 'arrival', 'unknown'].map((f) => [`color.phase.${f}`, ['page', 'panel', 'raised', 'hover', 'selected', 'map'].map((s) => `color.surface.${s}`)]),
];
const allSurf = [...surfaces, 'color.surface.map'];
p('## Texte sur les surfaces (WCAG 2.1, AA = 4,5:1)');
p();
p('Chaque jeton de texte, sur chaque surface où il peut apparaître (case vide : combinaison non prévue).');
p();
p(`| Texte | ${allSurf.map((s) => s.split('.').pop()).join(' | ')} |`);
p(`|---|${allSurf.map(() => '---:').join('|')}|`);
for (const [t, ss] of textTokens) {
    const cells = allSurf.map((s) => {
        if (!ss.includes(s)) return '';
        const r = contrast(hex(t), hex(s));
        return r1(r) + mark(r >= 4.5);
    });
    p(`| \`${t.replace('color.', '')}\` ${hex(t)} | ${cells.join(' | ')} |`);
}
p();
p(`Désactivé (\`text.disabled\` ${hex('color.text.disabled')}) : ${['panel', 'hover'].map((s) => `${s} ${r1(contrast(hex('color.text.disabled'), hex(`color.surface.${s}`)))}`).join(', ')} — exempté par WCAG, voulu sous le seuil.`);
p();

// Text on fills
p('## Texte sur les aplats');
p();
for (const [t, f] of [['color.text.on-accent', 'color.accent.fill'], ['color.text.on-urgent', 'color.status.urgent-fill'], ['color.text.on-warn', 'color.status.warn']]) {
    const r = contrast(hex(t), hex(f));
    p(`- \`${t.replace('color.', '')}\` sur \`${f.replace('color.', '')}\` : ${r1(r)}${mark(r >= 4.5)}`);
}
for (const f of ['ground', 'departure', 'cruise', 'arrival', 'unknown']) {
    const r = contrast(hex('color.text.on-warn'), hex(`color.phase.${f}`));
    p(`- \`text.on-warn\` sur \`phase.${f}\` (badge plein de T/O et T/D) : ${r1(r)}${mark(r >= 4.5)}`);
}
p();

// Non-text contrasts
p('## Contrastes hors texte (WCAG 1.4.11, 3:1)');
p();
const nonText = [
    ['color.border.control', ['panel', 'raised', 'hover']],
    ['color.border.focus', ['page', 'panel', 'raised', 'hover', 'selected', 'map']],
    ['color.status.ok', ['panel', 'raised', 'map']],
    ['color.status.warn', ['panel', 'raised', 'map']],
    ['color.status.urgent', ['panel', 'raised', 'map']],
    ['color.status.unknown', ['panel', 'raised']],
];
for (const [t, ss] of nonText) {
    p(`- \`${t.replace('color.', '')}\` ${hex(t)} : ${ss.map((s) => { const r = contrast(hex(t), hex(`color.surface.${s}`)); return `${s} ${r1(r)}${mark(r >= 3)}`; }).join(', ')}`);
}
p(`- \`status.urgent-fill\` ${hex('color.status.urgent-fill')} : panel ${r1(contrast(hex('color.status.urgent-fill'), hex('color.surface.panel')))} — non exigé : l'aplat est toujours bordé de \`status.urgent\`, qui porte le contraste.`);
p('- `border.default` et `border.subtle` ne sont pas soumis au 3:1 : ce sont des séparateurs, pas des contours de contrôle ; '
    + `${r1(contrast(hex('color.border.default'), hex('color.surface.panel')))} et ${r1(contrast(hex('color.border.subtle'), hex('color.surface.panel')))} sur panel.`);
p();

// Altitude ramps: palette F (13/10), a ramp of hue. Required, on its base map:
// every band at 3:1 at least (an icon is a mark); every pair of bands apart by
// ΔE 12 under the worst of the four visions and by 20 under normal sight;
// no band within ΔE 18 of the urgent red; none within 5 of a phase family (the
// label of the same aircraft); near the ground the most visible, cruise the least.
p('## Rampes d\'altitude (icône d\'avion sur la carte)');
p();
const bands = ['very-low', 'low', 'mid', 'high', 'cruise'];
const views4 = [(c) => c, ...Object.values(CVD).map((m) => (c) => simulate(c, m))];
const worstDE = (a, b) => Math.min(...views4.map((v) => deltaE(v(a), v(b))));
const famHex = ['ground', 'departure', 'cruise', 'arrival', 'unknown'].map((f) => hex(`color.phase.${f}`));
for (const [mode, bg] of [['dark', '#000000'], ['light', '#ffffff']]) {
    const vals = bands.map((b) => hex(`color.altitude.${mode}.${b}`));
    const cons = vals.map((v) => contrast(v, bg));
    let allWorst = Infinity, allNormal = Infinity;
    for (let i = 0; i < vals.length; i++) for (let j = i + 1; j < vals.length; j++) {
        allWorst = Math.min(allWorst, worstDE(vals[i], vals[j]));
        allNormal = Math.min(allNormal, deltaE(vals[i], vals[j]));
    }
    const urgent = Math.min(...vals.map((v) => worstDE(v, hex('color.status.urgent'))));
    const family = Math.min(...vals.flatMap((v) => famHex.map((f) => worstDE(v, f))));
    const order = cons[0] >= Math.max(...cons) && cons[4] <= Math.min(...cons);
    p(`- **${mode === 'dark' ? 'fond sombre' : 'fond clair'}** (sur ${bg}) : ${bands.map((b, i) => `${b} ${vals[i]} (${r1(cons[i])}${mark(cons[i] >= 3)})`).join(' · ')}`);
    p(`  - toutes les paires : ΔE ${r1(allNormal)} en vision normale${mark(allNormal >= 20)}, ${r1(allWorst)} au pire daltonisme${mark(allWorst >= 12)} ; au rouge d'urgence ${r1(urgent)}${mark(urgent >= 18)} ; à une famille de phase ${r1(family)}${mark(family >= 5)} ; le plus bas le plus visible, la croisière la plus discrète : ${order ? 'oui' : 'non ✗'}${order ? '' : (failures++, '')}`);
}
p();

// Palettes under colour-vision deficiency
const views = { normale: (c) => c, ...Object.fromEntries(Object.entries(CVD).map(([k, m]) => [k, (c) => simulate(c, m)])) };
function cvdTable(title, entries, threshold, note) {
    p(`### ${title}`);
    p();
    if (note) { p(note); p(); }
    p(`| Paire | ${Object.keys(views).join(' | ')} | minimum |`);
    p(`|---|${Object.keys(views).map(() => '---:').join('|')}|---:|`);
    let worst = Infinity;
    for (let i = 0; i < entries.length; i++) for (let j = i + 1; j < entries.length; j++) {
        const [a, ka] = entries[i], [b, kb] = entries[j];
        const ds = Object.values(views).map((v) => deltaE(v(hex(ka)), v(hex(kb))));
        const m = Math.min(...ds); worst = Math.min(worst, m);
        p(`| ${a} / ${b} | ${ds.map(r1).join(' | ')} | ${r1(m)}${mark(m >= threshold)} |`);
    }
    p();
    p(`Minimum : **${r1(worst)}** (exigence ≥ ${threshold}).`);
    p();
}
p('## Palettes porteuses de sens et daltonisme');
p();
p('ΔE76 dans l\'espace Lab, après simulation Machado et al. 2009 (sévérité 1). Repère : sous 10, deux pastilles de quelques pixels se confondent.');
p();
cvdTable('Familles de phase', ['ground', 'departure', 'cruise', 'arrival', 'unknown'].map((f) => [f, `color.phase.${f}`]), 20,
    'Inventaire du 12/10 : 1,8 (TAX / CRZ en deutéranopie) avec les dix couleurs actuelles.');
cvdTable('Sémantique : voix de l\'outil, urgence, attention, information',
    [['accent', 'color.accent.default'], ['urgence (aplat)', 'color.status.urgent-fill'], ['attention', 'color.status.warn'], ['information', 'color.status.info']], 15,
    'L\'urgence se compare à l\'accent par son aplat, qui est sa forme d\'apparition ; le texte d\'urgence (`status.urgent`) n\'apparaît jamais sans son pictogramme.');
cvdTable('Voyants (avec leurs formes : ● ▲ ■ ○)',
    [['ok', 'color.status.ok'], ['attention', 'color.status.warn'], ['panne', 'color.status.urgent'], ['inconnu', 'color.status.unknown']], 0,
    'La couleur n\'est pas seule : chaque voyant a sa forme. Le tableau dit ce que la couleur ajoute ; aucune exigence chiffrée.');

fs.writeFileSync(mdOut, out.join('\n') + '\n');
const n = flat.size;
console.log(`${n} jetons ; ${path.relative(root, cssOut)} et ${path.relative(root, mdOut)} écrits ; ${failures ? failures + ' exigence(s) non tenue(s)' : 'toutes les exigences tenues'}.`);
process.exit(failures ? 1 : 0);
